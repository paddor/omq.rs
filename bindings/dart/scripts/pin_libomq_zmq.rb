#!/usr/bin/env ruby
# frozen_string_literal: true

# Pin the build hook to an omq-libzmq release: read the release's SHA256SUMS
# and rewrite lib/src/hook/libomq_zmq.dart with the version and per-target
# digests.
#
# usage: ruby bindings/dart/scripts/pin_libomq_zmq.rb VERSION

require "open-uri"

TARGETS = %w[
  x86_64-unknown-linux-gnu
  aarch64-unknown-linux-gnu
  x86_64-apple-darwin
  aarch64-apple-darwin
  x86_64-pc-windows-msvc
].freeze
PIN = File.expand_path("../lib/src/hook/libomq_zmq.dart", __dir__)

version = ARGV.fetch(0) { abort "usage: #{$PROGRAM_NAME} VERSION" }
abort "bad version #{version}" unless version.match?(/\A\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?\z/)

url = "https://github.com/paddor/omq.rs/releases/download/omq-libzmq-v#{version}/SHA256SUMS"
sums = URI.parse(url).open(&:read).lines.to_h do |line|
  digest, name = line.split
  [name.delete_prefix("*"), digest]
end

pins = TARGETS.to_h do |target|
  asset = sums.keys.find { |name| name.match?(/\A(?:lib)?omq_zmq-#{Regexp.escape(target)}\.(?:so|dylib|dll)\z/) }
  abort "#{url}: no library for #{target}" unless asset
  digest = sums.fetch(asset)
  abort "#{url}: bad SHA-256 for #{asset}" unless digest.match?(/\A\h{64}\z/)

  [target, digest.downcase]
end

entries = pins.map { |target, digest| "  '#{target}': '#{digest}',\n" }.join
File.write(PIN, <<~DART.sub("ENTRIES\n", entries))
  // Generated by scripts/pin_libomq_zmq.rb from an omq-libzmq release's
  // SHA256SUMS. Do not edit.

  /// The omq-libzmq release whose prebuilt libraries the build hook downloads;
  /// empty while none is pinned.
  const libomqZmqVersion = '#{version}';

  /// SHA-256 of each prebuilt library of that release, by Rust target triple.
  const libomqZmqSha256 = <String, String>{
  ENTRIES
  };
DART
puts "pinned omq-libzmq #{version} in #{PIN}"
